_CATEGORIES = list(DOC_TEMPLATES.keys())


def generate(count: int = 20, seed: int = 42) -> int:
    """生成示例文档，返回生成篇数。

    每个分类先打乱模板池后顺序抽取：模板池足够大时同分类文档互不重复；
    模板不足时循环复用（仍保证稳定可复现）。
    """
    rng = random.Random(seed)
    KNOWLEDGE_DOCS_DIR.mkdir(parents=True, exist_ok=True)

    per_category = count // len(_CATEGORIES)
    generated = 0
    for cat in _CATEGORIES:
        templates = DOC_TEMPLATES[cat]
        pool = templates[:]
        rng.shuffle(pool)
        for i in range(per_category):
            content = pool[i % len(pool)]
            filename = f"{cat}_{i + 1:02d}.txt"
            (KNOWLEDGE_DOCS_DIR / filename).write_text(content, encoding="utf-8")
            generated += 1

    # 剩余数量随机分配
    while generated < count:
        cat = rng.choice(_CATEGORIES)
        content = rng.choice(DOC_TEMPLATES[cat])
        idx = len(list(KNOWLEDGE_DOCS_DIR.glob(f"{cat}_*.txt"))) + 1
        (KNOWLEDGE_DOCS_DIR / f"{cat}_{idx:02d}.txt").write_text(content, encoding="utf-8")
        generated += 1

    return generated


def main() -> None:
    parser = argparse.ArgumentParser(description="生成示例企业知识库文档")
    parser.add_argument("--count", "-n", type=int, default=20, help="文档总数")
    parser.add_argument("--seed", type=int, default=42, help="随机种子（保证可复现）")
    args = parser.parse_args()

    n = generate(args.count, args.seed)
    print(f"? 已生成 {n} 篇示例文档 → {KNOWLEDGE_DOCS_DIR}")


if __name__ == "__main__":
    main()
